/** t(lang, "key", { name: "..." }) — same keys as the app's t("key"). */
export function t(lang, key, vars) {
  let s = translations[lang]?.[key] ?? translations.bn[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}
/** Pick several keys at once — for passing a small set of words to a client component. */
export function pick(lang, keys) {
  return Object.fromEntries(keys.map((k) => [k, t(lang, k)]));
}
